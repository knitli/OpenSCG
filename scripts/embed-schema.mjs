// Copies schema/0.1/guide.schema.json into src/generated/schema.ts so the
// library works in any JavaScript runtime without file-system access.
// test/schema-embed.test.ts fails if the two drift apart.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync("schema/0.1/guide.schema.json", "utf8"));
mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/schema.ts",
  `// SPDX-FileCopyrightText: 2026 Knitli Inc.
// SPDX-License-Identifier: Apache-2.0
//
// GENERATED by scripts/embed-schema.mjs from schema/0.1/guide.schema.json.
// Do not edit by hand. Run: npm run embed-schema
export const GUIDE_SCHEMA_0_1 = ${JSON.stringify(schema, null, 2)} as const;
`,
);
